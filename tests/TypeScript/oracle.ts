// Refresh focused TypeScript execution oracles with the existing pinned esbuild
// toolchain. Node prepares reference output; Phasis executes original TS files.
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as Effect from "effect/Effect";
import * as FileSystem from "effect/FileSystem";
import { build } from "../../scripts/lib/build.ts";
import { emit, main, script } from "../../scripts/lib/cli.ts";
import * as Command from "../../scripts/lib/command.ts";

const here = path.dirname(fileURLToPath(import.meta.url));
const directory = path.join(here, "fixtures");
const types = [
  "number",
  "unknown",
  "Wrapper<Wrapper<number>>",
  "readonly [number, string?]",
  "{ value: number }",
  "(Value extends number ? number : never)",
];
const expressions = [
  "left() as TYPE + right()",
  "left() + right() as TYPE",
  "left() as TYPE * right()",
  "(left() as TYPE) ** right()",
  "left() as TYPE < right()",
  "left() < right() as TYPE",
  "left() as TYPE ? right() : zero()",
  "(false ? left() : right()) as TYPE",
  "left() as TYPE && right()",
  "left() as TYPE || right()",
  "(null as TYPE) ?? right()",
  "(null as TYPE)?.value",
  "(object as TYPE).value",
  "object.value as TYPE + object.value",
  "((value: TYPE) => value)(left())",
  "((value = left() as TYPE): TYPE => value)()",
  "((value?: TYPE): TYPE => value)(left())",
  "left() as TYPE === right()",
];
const matrix = [
  "// Generated by tests/TypeScript/oracle.ts.",
  "type Wrapper<T> = T;",
  "type Value = number;",
];
let index = 0;
for (const expression of expressions) {
  for (const type of types) {
    matrix.push(
      "{",
      "  const calls: string[] = [];",
      "  function left() { calls.push('left'); return 2; }",
      "  function right() { calls.push('right'); return 3; }",
      "  function zero() { calls.push('zero'); return 0; }",
      "  const object = { get value() { calls.push('getter'); return 5; } };",
      "  const result = " + expression.replaceAll("TYPE", type) + ";",
      "  console.log(JSON.stringify([" + index++ + ", result, calls]));",
      "}",
    );
  }
}
export const command = script("typescript-oracle", {
  description:
    "Refresh TypeScript execution oracles with native Node and pinned esbuild.",
  flags: {},
  run: (input) =>
    Effect.scoped(
      Effect.gen(function* () {
        if (input.dryRun)
          return yield* emit(
            input,
            { status: "planned", cases: index },
            JSON.stringify,
          );
        const fs = yield* FileSystem.FileSystem;
        yield* fs.writeFileString(
          path.join(directory, "differential.ts"),
          matrix.join("\n") + "\n",
        );
        const temporary = yield* fs.makeTempDirectoryScoped({
          prefix: "phasis-typescript-oracle-",
        });
        const results: string[] = [];
        for (const name of (yield* fs.readDirectory(directory))
          .filter((name) => /\.(?:ts|mts|cts)$/.test(name))
          .sort()) {
          const input = path.join(directory, name);
          const commonjs = name.endsWith(".cts");
          const output = path.join(
            temporary,
            commonjs ? "fixture.cjs" : "fixture.mjs",
          );
          if (name !== "assertions.ts") {
            const reference = (yield* Command.run({
              command: process.execPath,
              args: [input],
            })).stdout;
            yield* fs.writeFileString(input + ".expected.txt", reference);
            results.push(name + ": native Node");
            continue;
          }
          yield* build({
            entryPoints: [input],
            bundle: true,
            outfile: output,
            platform: "node",
            format: commonjs ? "cjs" : "esm",
            target: "esnext",
            logLevel: "silent",
            tsconfigRaw: {
              compilerOptions: {
                verbatimModuleSyntax: true,
                useDefineForClassFields: true,
              },
            },
          });
          const reference = (yield* Command.run({
            command: process.execPath,
            args: [output],
          })).stdout;
          yield* fs.writeFileString(input + ".expected.txt", reference);
          results.push(name + ": esbuild/Node");
        }
        yield* emit(input, { cases: index, fixtures: results }, JSON.stringify);
      }),
    ),
});
if (import.meta.main) main(command);
