// Refresh focused TypeScript execution oracles with the existing pinned esbuild
// toolchain. Node prepares reference output; Phasis executes original TS files.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { build } from '../Jsx/oracle/node_modules/esbuild/lib/main.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const directory = path.join(here, 'fixtures');
const types = [
  'number', 'unknown', 'Wrapper<Wrapper<number>>', 'readonly [number, string?]',
  '{ value: number }', '(Value extends number ? number : never)',
];
const expressions = [
  'left() as TYPE + right()', 'left() + right() as TYPE',
  'left() as TYPE * right()', '(left() as TYPE) ** right()',
  'left() as TYPE < right()', 'left() < right() as TYPE',
  'left() as TYPE ? right() : zero()', '(false ? left() : right()) as TYPE',
  'left() as TYPE && right()', 'left() as TYPE || right()',
  '(null as TYPE) ?? right()', '(null as TYPE)?.value',
  '(object as TYPE).value', 'object.value as TYPE + object.value',
  '((value: TYPE) => value)(left())',
  '((value = left() as TYPE): TYPE => value)()',
  '((value?: TYPE): TYPE => value)(left())',
  'left() as TYPE === right()',
];
const matrix = ['// Generated by tests/TypeScript/oracle.mjs.',
  'type Wrapper<T> = T;', 'type Value = number;'];
let index = 0;
for (const expression of expressions) {
  for (const type of types) {
    matrix.push(
      '{', '  const calls: string[] = [];',
      "  function left() { calls.push('left'); return 2; }",
      "  function right() { calls.push('right'); return 3; }",
      "  function zero() { calls.push('zero'); return 0; }",
      "  const object = { get value() { calls.push('getter'); return 5; } };",
      '  const result = ' + expression.replaceAll('TYPE', type) + ';',
      '  console.log(JSON.stringify([' + index++ + ', result, calls]));', '}',
    );
  }
}
fs.writeFileSync(path.join(directory, 'differential.ts'), matrix.join('\n') + '\n');
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'phasis-typescript-oracle-'));
try {
  for (const name of fs.readdirSync(directory).filter(name => /\.(?:ts|mts|cts)$/.test(name)).sort()) {
    const input = path.join(directory, name);
    const commonjs = name.endsWith('.cts');
    const output = path.join(temporary, commonjs ? 'fixture.cjs' : 'fixture.mjs');
    if (name !== 'assertions.ts') {
      const reference = execFileSync(process.execPath, [input], { encoding: 'utf8' });
      fs.writeFileSync(input + '.expected.txt', reference);
      console.log(name + ': captured native Node type-stripping oracle');
      continue;
    }
    await build({
      entryPoints: [input], bundle: true, outfile: output,
      platform: 'node', format: commonjs ? 'cjs' : 'esm', target: 'esnext',
      logLevel: 'silent',
      tsconfigRaw: { compilerOptions: { verbatimModuleSyntax: true, useDefineForClassFields: true } },
    });
    const reference = execFileSync(process.execPath, [output], { encoding: 'utf8' });
    fs.writeFileSync(input + '.expected.txt', reference);
    console.log(name + ': captured esbuild/Node oracle');
  }
} finally {
  fs.rmSync(temporary, { recursive: true, force: true });
}
