'use strict';
const { Readable, Writable, Transform, PassThrough } = require('stream');
const { pipeline, finished } = require('stream/promises');
const { Buffer } = require('buffer');
require('./helpers.cjs').run(async () => {
  const output = [];
  const chunks = [];
  const transform = new Transform({ transform(chunk, encoding, callback) { callback(null, chunk.toString().toUpperCase()); } });
  const destination = new Writable({ highWaterMark: 1, write(chunk, encoding, callback) { chunks.push(chunk.toString()); process.nextTick(callback); } });
  await pipeline(Readable.from(['hello', 'world']), transform, destination);
  output.push(['pipeline', chunks, destination.writableFinished, transform.destroyed]);
  const asyncValues = [];
  for await (const chunk of Readable.from([1, 2, 3])) asyncValues.push(chunk);
  output.push(['async-iterate', asyncValues]);
  const corked = [];
  const sink = new Writable({ write(chunk, encoding, callback) { corked.push(['single', chunk.toString()]); callback(); }, writev(chunks, callback) { corked.push(['batch', chunks.map((item) => item.chunk.toString())]); callback(); } });
  sink.cork();
  sink.write('a');
  sink.write('b');
  sink.uncork();
  sink.end('c');
  await finished(sink);
  output.push(['writev', corked, sink.writableEnded]);
  const backpressure = [];
  let complete;
  const bounded = new Writable({ highWaterMark: 1, write(chunk, encoding, callback) { complete = callback; } });
  backpressure.push(bounded.write('x'), bounded.writableNeedDrain, bounded.writableLength);
  bounded.on('drain', () => backpressure.push('drain'));
  complete();
  await new Promise((resolve) => process.nextTick(resolve));
  bounded.end();
  await finished(bounded);
  output.push(['backpressure', backpressure]);
  const bytes = Readable.from([Buffer.from([0xf0, 0x9f]), Buffer.from([0x8c, 0x8d])]);
  bytes.setEncoding('utf8');
  let text = '';
  for await (const chunk of bytes) text += chunk;
  output.push(['decoder', text]);
  const broken = new Transform({ transform(chunk, encoding, callback) { callback(new Error('pipeline failed')); } });
  try { await pipeline(Readable.from(['x']), broken, new PassThrough()); } catch (error) { output.push(['pipeline-error', error.message, broken.destroyed]); }
  output.push(['operators', await Readable.from([1, 2, 3, 4]).map(async (value) => value * 2).filter((value) => value > 4).toArray()]);
  return output;
});
