'use strict';
const events = require('events');
const { EventEmitter, once, on, errorMonitor, captureRejectionSymbol } = events;
require('./helpers.cjs').run(async () => {
  const output = [];
  const emitter = new EventEmitter();
  const calls = [];
  const second = () => calls.push('second');
  emitter.on('value', function () { calls.push(this === emitter ? 'first' : 'bad-this'); emitter.removeListener('value', second); });
  emitter.on('value', second);
  emitter.prependOnceListener('value', () => calls.push('once'));
  output.push(['emit-return', emitter.emit('value'), emitter.emit('missing')]);
  emitter.emit('value');
  output.push(['mutation', calls, emitter.listenerCount('value'), emitter.rawListeners('value').length]);
  const symbol = Symbol('key');
  emitter.on(symbol, second);
  output.push(['symbol', emitter.eventNames().map(String), emitter.listenerCount(symbol, second)]);
  const monitored = new EventEmitter();
  const monitor = [];
  monitored.on(errorMonitor, (error) => monitor.push(error.message));
  try { monitored.emit('error', new Error('expected')); } catch (error) { monitor.push(error.message); }
  output.push(['error-monitor', monitor]);
  const captured = new EventEmitter({ captureRejections: true });
  captured.on('work', async (value) => { throw new Error(value); });
  const rejection = new Promise((resolve) => { captured[captureRejectionSymbol] = (error, name, value) => resolve([error.message, name, value]); });
  captured.emit('work', 'rejected');
  output.push(['capture', await rejection]);
  const awaited = once(emitter, 'ready');
  emitter.emit('ready', 1, 2);
  output.push(['once', await awaited, emitter.listenerCount('ready'), emitter.listenerCount('error')]);
  const controller = new AbortController();
  const aborted = once(emitter, 'never', { signal: controller.signal });
  controller.abort('stop');
  try { await aborted; } catch (error) { output.push(['abort', error.name, error.code, error.cause, emitter.listenerCount('never')]); }
  const iterator = on(emitter, 'item', { close: ['finish'] });
  emitter.emit('item', 'a');
  emitter.emit('item', 'b');
  emitter.emit('finish');
  const values = [];
  for await (const item of iterator) values.push(item);
  output.push(['iterator', values, emitter.listenerCount('item'), emitter.listenerCount('finish')]);
  const listenerController = new AbortController();
  let count = 0;
  const disposable = events.addAbortListener(listenerController.signal, () => count++);
  disposable[Symbol.dispose]();
  listenerController.abort();
  output.push(['disposed', count]);
  return output;
});
