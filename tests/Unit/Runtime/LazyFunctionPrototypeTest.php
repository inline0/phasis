<?php

declare(strict_types=1);

namespace Phasis\Tests\Unit\Runtime;

use Phasis\Engine;
use Phasis\Value\JsFunction;
use Phasis\Value\JsObject;
use Phasis\Value\JsUndefined;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;

final class LazyFunctionPrototypeTest extends TestCase
{
    /** @return iterable<string, array{bool}> */
    public static function executionModes(): iterable
    {
        yield 'bytecode' => [false];
        yield 'interpreter' => [true];
    }

    #[DataProvider('executionModes')]
    public function testPrototypeObservationsMatchNode(bool $interpret): void
    {
        $source = file_get_contents(__DIR__ . '/fixtures/lazy-function-prototype.js');
        $oracle = file_get_contents(__DIR__ . '/fixtures/lazy-function-prototype.expected.json');
        self::assertIsString($source);
        self::assertIsString($oracle);
        $engine = new Engine();
        if ($interpret) {
            $engine->setExecutionBudget(1_000_000);
        }

        // The fixture snapshot is generated by Node v26.12.0.
        self::assertSame(json_decode($oracle, true, flags: JSON_THROW_ON_ERROR), $engine->eval($source));
    }

    public function testUnobservedPrototypeDoesNotRequireCycleCollection(): void
    {
        $engine = new Engine();
        $engine->eval('function factory() { return function () { return 1; }; } factory(); factory();');
        gc_collect_cycles();
        $wasEnabled = gc_enabled();
        gc_disable();
        $runs = gc_status()['runs'];

        try {
            foreach (['function () {}', 'factory()'] as $expression) {
                $engine->eval('void (globalThis.temporary = ' . $expression . ');');
                $function = $engine->getGlobalEnv()->get('temporary');
                self::assertInstanceOf(JsFunction::class, $function);
                $reference = \WeakReference::create($function);
                self::assertTrue($function->hasOwnProperty('prototype'));
                self::assertContains('prototype', $function->getOwnPropertyNames());
                $engine->setGlobalJsValue('temporary', JsUndefined::instance());
                unset($function);

                self::assertTrue($reference->get() === null, 'An unobserved prototype must not create a cycle.');
            }
            self::assertSame($runs, gc_status()['runs']);
        } finally {
            if ($wasEnabled) {
                gc_enable();
            }
        }
    }

    public function testAnEscapedPrototypeKeepsItsConstructorAlive(): void
    {
        $engine = new Engine();
        $engine->eval('void (globalThis.temporary = function () {});');
        $function = $engine->getGlobalEnv()->get('temporary');
        self::assertInstanceOf(JsFunction::class, $function);
        $reference = \WeakReference::create($function);
        $prototype = $function->get('prototype');
        self::assertInstanceOf(JsObject::class, $prototype);
        $engine->setGlobalJsValue('temporary', JsUndefined::instance());
        unset($function);
        gc_collect_cycles();

        self::assertTrue(self::readFunctionReference($reference) !== null, 'The constructor must retain its function.');
        self::assertSame(self::readFunctionReference($reference), $prototype->get('constructor'));
        unset($prototype);
        gc_collect_cycles();
        self::assertTrue(self::readFunctionReference($reference) === null, 'The cycle must remain collectable.');
    }

    /**
     * @param \WeakReference<JsFunction> $reference
     * @phpstan-impure
     */
    private static function readFunctionReference(\WeakReference $reference): ?JsFunction
    {
        return $reference->get();
    }

    public function testRawDescriptorCopyContainsTheRealPrototype(): void
    {
        $engine = new Engine();
        $engine->eval('void (globalThis.temporary = function () {});');
        $function = $engine->getGlobalEnv()->get('temporary');
        self::assertInstanceOf(JsFunction::class, $function);
        $descriptor = $function->getOwnPropertyDescriptorRaw('prototype');
        self::assertNotNull($descriptor);
        $prototype = $descriptor->value;
        self::assertInstanceOf(JsObject::class, $prototype);
        self::assertSame($function, $prototype->get('constructor'));
        self::assertSame($prototype, $function->get('prototype'));
    }

    public function testPublicPropertyMapContainsTheRealPrototype(): void
    {
        $engine = new Engine();
        $engine->eval('void (globalThis.temporary = function () {});');
        $function = $engine->getGlobalEnv()->get('temporary');
        self::assertInstanceOf(JsFunction::class, $function);
        $descriptor = $function->getProperties()->get('prototype');
        self::assertNotNull($descriptor);
        $prototype = $descriptor->value;
        self::assertInstanceOf(JsObject::class, $prototype);
        self::assertSame($function, $prototype->get('constructor'));
        self::assertSame($prototype, $function->get('prototype'));
    }

    #[DataProvider('executionModes')]
    public function testMaterializationUsesTheDefiningRealmIntrinsic(bool $interpret): void
    {
        $engine = new Engine(node: true);
        if ($interpret) {
            $engine->setExecutionBudget(1_000_000);
        }
        self::assertSame(array_fill(0, 18, true), $engine->eval(<<<'JS'
const vm = require('node:vm');
const sandbox = vm.createContext({});
const foreign = vm.runInContext('(function Foreign() {})', sandbox);
const foreignObjectPrototype = vm.runInContext('Object.prototype', sandbox);
vm.runInContext('Object = function Replacement() {}', sandbox);
const firstRead = Reflect.get(new Proxy(foreign, {}), 'prototype', 17);
const observations = [
  Object.getPrototypeOf(firstRead) === foreignObjectPrototype,
  Object.getPrototypeOf(firstRead) !== Object.prototype,
  firstRead.constructor === foreign,
  Object.getPrototypeOf(new foreign()) === firstRead,
  Object.getOwnPropertyDescriptor(foreign, 'prototype').value === firstRead
];
function construct(Constructor) { return new Constructor(); }
// Warm the function and constructor so later calls include the VM inline path.
construct(foreign); construct(foreign);
for (const replacement of [null, undefined, {}]) {
  foreign.prototype = replacement;
  const expected = replacement && typeof replacement === 'object' ? replacement : foreignObjectPrototype;
  observations.push(
    Object.getPrototypeOf(new foreign()) === expected,
    Object.getPrototypeOf(construct(foreign)) === expected,
    Object.getPrototypeOf(Reflect.construct(foreign, [])) === expected,
    Object.getPrototypeOf(new (foreign.bind(null))()) === expected
  );
}
const other = vm.runInNewContext('(function Other() {})');
observations.push(Object.getPrototypeOf(other.prototype) !== foreignObjectPrototype);
observations;
JS));
    }
}
